"""Deterministic synthetic training data for LoRA fine-tuning the bounded
rewriter on multi-fact sentence fusion (FORBIDDEN.md's offline LoRA
fine-tuning exception, 2026-10-16).

Generated by code, never scraped, never a real document -- every example
is a template filled with synthetic names/numbers/dates/units drawn from
fixed pools below, matching FORBIDDEN.md's "training data must be synthetic
and deterministically generated" condition.

Two template families, blended, not one replacing the other:
  - GENERIC_TEMPLATES span many unrelated small topics (not just one
    domain) so the adapter learns the general skill ("fuse N given facts,
    drop none, keep every citation") rather than overfitting to one
    domain's phrasing -- the same cross-domain-generality principle
    EXP-069 established for the reasoning signals, applied here to the
    rewriter's training data.
  - LEGAL_TEMPLATES match the exact short-declarative style of the
    original EXP-048/064 failure case (lease terms, named parties and
    roles, dates) -- added after EXP-073 measured that a generic-only
    training set taught the fusion skill well within its own distribution
    (held-out pass rate 0.0 -> 1.0) but produced a new degenerate
    citation-repetition failure on that original, differently-styled case.
    This tests whether matching the target style, not just more epochs or
    a higher LoRA rank, is what was actually missing. Using "Lessee"/
    "Lessor" here is not the domain-hardcoding EXP-069 removed from the
    reasoning signals -- the rewriter never makes a reasoning decision
    based on these words, it only rewrites whatever content it is given,
    so training it on one more sentence *style* among several doesn't
    reintroduce a domain-specific control-flow branch anywhere.

Each example is exactly the shape lab.common.real_rewriter.build_prompt
already consumes: a "leaf" with 1-4 findings, each a
{"finding_id", "statement", "citation"} dict. The target is a single
sentence/short paragraph that restates every statement and keeps every
citation marker -- built by deterministic templated fusion (fixed
connective words), not by another model, so the dataset itself contains no
generative-model output.
"""

from __future__ import annotations

import random

NAMES = [
    "Alex Chen", "Priya Nair", "Jorge Alvarez", "Fatima Khan", "Ingrid Olsen",
    "Marcus Webb", "Aiko Tanaka", "Samuel Owusu", "Elena Petrova", "Devon Clarke",
]
UNITS = ["kg", "days", "MPa", "percent", "hours", "liters", "meters", "points"]
ITEMS = ["component", "shipment", "device", "sample", "account", "ticket", "module", "batch"]
VERBS_PAST = ["measured", "recorded", "reported", "logged", "submitted", "approved", "flagged", "updated"]
GENERIC_TEMPLATES = [
    lambda n, v, it, num, unit: f"{n} {v} the {it} at {num} {unit}.",
    lambda n, v, it, num, unit: f"The {it} assigned to {n} reached {num} {unit}.",
    lambda n, v, it, num, unit: f"{n} noted that the {it} must not exceed {num} {unit}.",
    lambda n, v, it, num, unit: f"On review, {n} found the {it}'s value at {num} {unit}.",
    lambda n, v, it, num, unit: f"{n} confirmed the {it} was within {num} {unit} of the limit.",
]

# Each term paired with its real unit type -- "security deposit is 20
# days" is structurally fine for the fusion skill but needlessly
# incoherent; matching EXP-048's own convention (time terms in days,
# money terms in INR) keeps the synthetic data closer to realistic.
LEGAL_TERMS_DAYS = ["notice period", "cure period", "grace period", "renewal term"]
LEGAL_TERMS_MONEY = ["security deposit", "rent"]
ROLES = ["Lessee", "Lessor", "Tenant", "Landlord", "Guarantor"]
LEGAL_ACTIONS = ["sublet the premises", "assign this agreement", "alter the fixtures", "remove the fittings"]
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]


def _legal_term_and_amount(rng: random.Random) -> tuple[str, str]:
    if rng.random() < 0.5:
        return rng.choice(LEGAL_TERMS_DAYS), f"{rng.randint(1, 60)} days"
    return rng.choice(LEGAL_TERMS_MONEY), f"INR {rng.randint(1000, 99000)}"


def _legal_date(rng: random.Random) -> str:
    return f"{rng.randint(1, 28)} {rng.choice(MONTHS)} {rng.randint(2020, 2025)}"


def _legal_term_statement(rng: random.Random) -> str:
    term, amount = _legal_term_and_amount(rng)
    return f"The {term} is {amount}."


LEGAL_TEMPLATES = [
    _legal_term_statement,
    lambda rng: f"{rng.choice(NAMES)} is the {rng.choice(ROLES)}.",
    lambda rng: f"The lease was signed on {_legal_date(rng)}.",
    lambda rng: f"The {rng.choice(ROLES)} shall not {rng.choice(LEGAL_ACTIONS)} unless the {rng.choice(ROLES)} consents.",
]


def _make_statement(rng: random.Random) -> str:
    if rng.random() < 0.5:
        template = rng.choice(GENERIC_TEMPLATES)
        return template(
            rng.choice(NAMES),
            rng.choice(VERBS_PAST),
            rng.choice(ITEMS),
            rng.randint(1, 999),
            rng.choice(UNITS),
        )
    template = rng.choice(LEGAL_TEMPLATES)
    return template(rng)


CONNECTIVES = ["Separately,", "In addition,", "At the same time,", "Elsewhere,", "Meanwhile,"]
_FIRST_NAMES = {n.split()[0] for n in NAMES}


def _fuse(statements_with_cites: list[tuple[str, str]], rng: random.Random) -> str:
    """Deterministic templated fusion: first statement starts the paragraph,
    each following one is joined by a randomly chosen (but fixed-vocabulary)
    connective, every citation marker kept exactly as given.
    """
    parts = []
    for i, (statement, cite) in enumerate(statements_with_cites):
        body = statement.rstrip(".")
        if i == 0:
            parts.append(f"{body} [{cite}]")
        else:
            connective = rng.choice(CONNECTIVES)
            first_word = body.split()[0] if body.split() else ""
            # Don't lowercase a leading proper name ("Alex Chen confirmed...")
            # -- only a leading common word ("The...", "On review...") should
            # fold into the connective's clause.
            lowered = body if first_word in _FIRST_NAMES else body[0].lower() + body[1:]
            parts.append(f"{connective} {lowered} [{cite}]")
    return ". ".join(parts) + "."


def make_example(rng: random.Random, n_facts: int) -> dict:
    statements = [_make_statement(rng) for _ in range(n_facts)]
    cites = [f"CITE-{rng.randrange(10**6):06d}" for _ in range(n_facts)]
    findings = [{"finding_id": f"F{i:03d}", "statement": s, "citation": c} for i, (s, c) in enumerate(zip(statements, cites))]
    target = _fuse(list(zip(statements, cites)), rng)
    return {
        "leaf_id": f"SYN{rng.randrange(10**7):07d}",
        "title": "Synthetic",
        "finding_ids": [f["finding_id"] for f in findings],
        "findings": findings,
        "target": target,
    }


def generate_dataset(n_examples: int, seed: int, min_facts: int = 2, max_facts: int = 4) -> list[dict]:
    rng = random.Random(seed)
    return [make_example(rng, rng.randint(min_facts, max_facts)) for _ in range(n_examples)]
