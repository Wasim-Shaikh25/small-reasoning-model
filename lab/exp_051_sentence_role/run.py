"""EXP-051: sentence role-tagging classifier (direct answer / supporting
evidence / background / contradiction).

Replaces lab.common.verify.coverage_check's binary found/missing/
conflicted status with a 4-way role label per shortlisted sentence, so
the page-wise writer knows HOW to use a sentence, not just whether it
passed verification -- the "mark how to use them" step of AGENT.md's
word-by-word relevance cascade, depending on EXP-049's relevance score
as one input feature, per that exploration's own named follow-up.

Multinomial logistic regression (sklearn), the same head shape as
EXP-011's next_action_head, trained on labels generated by construction
(each scenario's true role is known because it was built that way, the
same approach EXP-011 itself uses for its own three labels) -- never on
an externally-sourced dataset. Three features, all already-measured,
non-generative signals:
  - NLI entail/contradict probability (lab.common.nli.judge, the same
    lexical judge EXP-011 already uses) between the sentence and a
    claim built directly from the ask -- separates direct_answer
    (entails) and contradiction (contradicts) from the other two roles.
  - Ask-relevance coverage (lab.common.relevance.ask_relevance) --
    separates supporting_evidence (on-topic but doesn't state the fact)
    from background (genuinely unrelated); NLI alone can't make this
    distinction since both score near-neutral against the claim.
  - Sentence position (synthetic, 0-1) -- a real pipeline's shortlist
    has a position for every candidate; included as its own feature per
    the todo's own method, even though this generated set does not make
    it informative by construction (reported honestly in scale_down,
    not hidden).
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from lab.common.harness import Run
from lab.common.nli import judge
from lab.common.relevance import ask_relevance
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import train_test_split

FILES = [
    "lab/exp_051_sentence_role/run.py",
    "lab/common/nli.py",
    "lab/common/relevance.py",
    "lab/common/verify.py",
    "lab/exp_011_decision_heads/run.py",
    "data/exp_051_sentence_role/items.json",
]

SLOTS = [
    ("notice period", "30 days", "45 days"),
    ("security deposit", "INR 50000", "INR 75000"),
    ("rent", "INR 25000", "INR 40000"),
    ("cure period", "10 days", "20 days"),
]

BACKGROUND_SENTENCES = [
    "The building has a garden and a stone bench.",
    "The weather in Mumbai is pleasant during the monsoon season.",
    "The lobby was repainted last year in a light shade of blue.",
    "Visitors must sign in at the front desk before entering.",
]

ROLES = ("direct_answer", "supporting_evidence", "background", "contradiction")


def scenario(rng: random.Random, role: str) -> dict:
    slot, truth, other = rng.choice(SLOTS)
    ask = f"What is the {slot}?"
    claim = f"The {slot} is {truth}."
    position = rng.random()
    if role == "direct_answer":
        sentence = f"The {slot} is {truth}."
    elif role == "supporting_evidence":
        sentence = f"The {slot} was agreed upon by both parties and recorded in the signed lease."
    elif role == "contradiction":
        sentence = f"The {slot} is {other}."
    else:
        sentence = rng.choice(BACKGROUND_SENTENCES)
    return {"ask": ask, "claim": claim, "sentence": sentence, "role": role, "position": round(position, 4)}


def features(item: dict) -> list[float]:
    probs = judge(item["sentence"], item["claim"])
    relevance = ask_relevance(item["ask"], item["sentence"])
    return [probs["entail"], probs["neutral"], probs["contradict"], relevance["coverage"] or 0.0, item["position"]]


def main():
    run = Run("EXP-051", "exp_051_sentence_role")
    rng = random.Random(51)
    items = []
    for role in ROLES:
        for _ in range(120):
            items.append(scenario(rng, role))

    x = [features(item) for item in items]
    y = [item["role"] for item in items]
    x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.25, random_state=51, stratify=y)

    model = LogisticRegression(max_iter=500)
    model.fit(x_train, y_train)
    pred = model.predict(x_test)
    accuracy = float(model.score(x_test, y_test))

    by_role = {}
    for role in ROLES:
        role_indices = [i for i, gold in enumerate(y_test) if gold == role]
        role_correct = sum(1 for i in role_indices if pred[i] == role)
        by_role[role] = {"n": len(role_indices), "correct": role_correct, "accuracy": round(role_correct / len(role_indices), 4) if role_indices else None}

    confusion = {gold_role: {pred_role: 0 for pred_role in ROLES} for gold_role in ROLES}
    for gold, predicted in zip(y_test, pred):
        confusion[gold][predicted] += 1

    run.write_json("items.json", items[:40])

    metrics = {
        "train": len(x_train),
        "test": len(x_test),
        "test_accuracy": round(accuracy, 4),
        "by_role": by_role,
        "confusion_matrix": confusion,
    }

    prose = (
        f"4-way role classifier: test accuracy {metrics['test_accuracy']} on {metrics['test']} held-out items "
        f"({len(x_train)} training). Per-role accuracy: " + ", ".join(f"{r}={by_role[r]['accuracy']}" for r in ROLES) + ". "
        f"Confusion matrix: {confusion}."
    )

    all_roles_above_floor = all((by_role[r]["accuracy"] or 0) >= 0.8 for r in ROLES)

    conclusion = (
        "The three features separate all four roles cleanly on this generated set: NLI entailment isolates "
        "direct_answer, NLI contradiction isolates contradiction, and ask-relevance coverage is what actually "
        "separates supporting_evidence from background -- a distinction NLI alone cannot make, since both "
        "score near-neutral against the direct claim. This is the real reason EXP-049's relevance score is a "
        "load-bearing input feature here, not an optional extra."
        if all_roles_above_floor
        else "At least one role did not classify cleanly -- see confusion_matrix for exactly which roles are "
        "confused with which, reported as measured."
    )

    run.finish(
        title="Sentence role-tagging classifier (direct answer / supporting evidence / background / contradiction)",
        goal=(
            "Replace the current binary found/missing/conflicted status (lab/common/verify.coverage_check) "
            "with a 4-way role label per shortlisted sentence -- direct_answer, supporting_evidence, "
            "background, contradiction -- so the page-wise writer knows how to use each sentence."
        ),
        method=(
            "Multinomial logistic regression (sklearn), trained on 480 scenarios generated by construction "
            "(4 roles x 120 each, so the gold label is known with certainty, the same approach EXP-011 uses "
            "for its own labels) across 4 slot/value fixtures plus a small background-sentence pool. Features: "
            "lexical NLI entail/neutral/contradict probability (lab.common.nli.judge) between the candidate "
            "sentence and a claim built from the ask, ask-relevance coverage (lab.common.relevance."
            "ask_relevance), and a synthetic sentence-position value. 75/25 train/test split, stratified."
        ),
        metrics=metrics,
        results_prose=prose,
        conclusion=conclusion,
        scale_down=(
            "Labels are generated by construction from 4 slot/value fixtures and a 4-sentence background "
            "pool, not from a real document's actual shortlist -- the classifier has not been measured on "
            "real documents' sentences, only on this synthetic set. The position feature is a random float "
            "with no relationship to role in this generated set (a real pipeline's shortlist would have a "
            "real position-to-role correlation this fixture cannot represent), so this run cannot say "
            "whether position actually helps versus being inert; the model may be relying on it by chance. "
            "supporting_evidence/background are each drawn from a small fixed sentence template/pool, not a "
            "broad distribution of real phrasings."
        ),
        referenced_files=FILES,
        follow_ups=[
            "Measure against a real document's actual shortlisted sentences (not generated-by-construction "
            "labels) once a labeled real-document fixture exists, to check whether accuracy holds outside "
            "this generated set's narrow phrasing.",
        ],
        models_used=(
            "Multinomial logistic regression (sklearn), the same head shape as EXP-011's next_action_head. "
            "Features come from lab.common.nli.judge (lexical, deterministic) and lab.common.relevance."
            "ask_relevance (lexical, deterministic). No generative model, no neural encoder."
        ),
    )

    print(f"test_accuracy: {accuracy}")
    print("by_role:", {r: by_role[r]["accuracy"] for r in ROLES})


if __name__ == "__main__":
    main()
